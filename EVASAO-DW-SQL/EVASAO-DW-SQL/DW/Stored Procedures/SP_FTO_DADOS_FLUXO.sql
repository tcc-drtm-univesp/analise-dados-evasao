		(ORIGEM.QT_CONCLUINTE					IS NULL OR (DESTINO.QT_CONCLUINTE					IS NULL AND DESTINO.QT_CONCLUINTE				 IS NOT NULL)	OR	(ORIGEM.QT_CONCLUINTE					IS NOT NULL AND DESTINO.QT_CONCLUINTE						IS NULL))	OR
		(ORIGEM.QT_DESISTENCIA					IS NULL OR (DESTINO.QT_DESISTENCIA					IS NULL AND DESTINO.QT_DESISTENCIA				 IS NOT NULL)	OR	(ORIGEM.QT_DESISTENCIA					IS NOT NULL AND DESTINO.QT_DESISTENCIA						IS NULL))	OR
		(ORIGEM.QT_FALECIDO						IS NULL OR (DESTINO.QT_FALECIDO						IS NULL AND DESTINO.QT_FALECIDO					 IS NOT NULL)	OR	(ORIGEM.QT_FALECIDO						IS NOT NULL AND DESTINO.QT_FALECIDO							IS NULL))	OR
		(ORIGEM.VL_TAP							IS NULL OR (DESTINO.VL_TAP							IS NULL AND DESTINO.VL_TAP						 IS NOT NULL)	OR	(ORIGEM.VL_TAP							IS NOT NULL AND DESTINO.VL_TAP								IS NULL))	OR
		(ORIGEM.VL_TCA							IS NULL OR (DESTINO.VL_TCA							IS NULL AND DESTINO.VL_TCA						 IS NOT NULL)	OR	(ORIGEM.VL_TCA							IS NOT NULL AND DESTINO.VL_TCA								IS NULL))	OR
