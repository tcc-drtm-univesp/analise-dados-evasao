	--	(ORIGEM.NU_ANO_INGRESSO					IS NULL	OR (DESTINO.NU_ANO_INGRESSO					IS NULL AND DESTINO.NU_ANO_INGRESSO				 IS NOT NULL)	OR	(ORIGEM.NU_ANO_INGRESSO					IS NOT NULL AND DESTINO.NU_ANO_INGRESSO						IS NULL))	OR
