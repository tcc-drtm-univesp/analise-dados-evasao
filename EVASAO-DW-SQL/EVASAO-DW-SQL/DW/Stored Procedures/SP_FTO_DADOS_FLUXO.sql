		(ORIGEM.VL_TDAN							IS NULL OR (DESTINO.VL_TDAN							IS NULL AND DESTINO.VL_TDAN						 IS NOT NULL)	OR	(ORIGEM.VL_TDAN							IS NOT NULL AND DESTINO.VL_TDAN								IS NULL))
