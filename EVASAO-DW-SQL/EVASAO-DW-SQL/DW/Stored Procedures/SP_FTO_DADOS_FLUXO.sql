		 , DESTINO.NU_PRAZO_ACOMPANHAMENTO		= ORIGEM.NU_PRAZO_ACOMPANHAMENTO		
		 , DESTINO.NU_ANO_MAXIMO_ACOMPANHAMENTO	= ORIGEM.NU_ANO_MAXIMO_ACOMPANHAMENTO	
		 , DESTINO.QT_INGRESSANTE				= ORIGEM.QT_INGRESSANTE				
		 , DESTINO.QT_PERMANENCIA				= ORIGEM.QT_PERMANENCIA				
		 , DESTINO.QT_CONCLUINTE				= ORIGEM.QT_CONCLUINTE				
		 , DESTINO.QT_DESISTENCIA				= ORIGEM.QT_DESISTENCIA				
		 , DESTINO.QT_FALECIDO					= ORIGEM.QT_FALECIDO					
		 , DESTINO.VL_TAP						= ORIGEM.VL_TAP						
		 , DESTINO.VL_TCA						= ORIGEM.VL_TCA						
		 , DESTINO.VL_TDA						= ORIGEM.VL_TDA						
